CREATE TABLE IF NOT EXISTS cuentas (
    id BIGINT PRIMARY KEY,
    titular VARCHAR(150) NOT NULL,
    saldo DECIMAL(19, 2) NOT NULL CHECK (saldo >= 0),
    moneda CHAR(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS transferencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_origen_id BIGINT NOT NULL REFERENCES cuentas(id),
    cuenta_destino_id BIGINT NOT NULL REFERENCES cuentas(id),
    importe DECIMAL(17, 2) NOT NULL CHECK (importe > 0),
    moneda CHAR(3) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CHECK (cuenta_origen_id <> cuenta_destino_id)
);

CREATE TABLE IF NOT EXISTS incidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transferencia_id BIGINT NOT NULL REFERENCES transferencias(id),
    regla VARCHAR(80) NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    prioridad VARCHAR(20) NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    estado VARCHAR(30) NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'RESUELTA')),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNIQUE (transferencia_id, regla)
);

CREATE TABLE IF NOT EXISTS cambios_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL REFERENCES incidencias(id),
    estado_anterior VARCHAR(30) NOT NULL,
    estado_nuevo VARCHAR(30) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

