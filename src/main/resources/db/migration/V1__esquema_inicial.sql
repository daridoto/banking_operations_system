-- V1: esquema inicial de Countercheck.
-- Una migración aplicada no se modifica nunca: cualquier cambio va en una V2, V3...

-- Clientes del banco: personas (DNI/NIE) o empresas (CIF).
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('FISICA', 'JURIDICA')),
    nombre VARCHAR(80),
    apellidos VARCHAR(120),
    razon_social VARCHAR(150),
    documento VARCHAR(9) NOT NULL UNIQUE,
    estado VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL CHECK (estado IN ('ACTIVO', 'BAJA')),
    fecha_alta DATE DEFAULT CURRENT_DATE NOT NULL,
    -- Una persona tiene nombre y apellidos; una empresa, razón social. Nunca ambos.
    CHECK ((tipo = 'FISICA' AND nombre IS NOT NULL AND apellidos IS NOT NULL AND razon_social IS NULL)
        OR (tipo = 'JURIDICA' AND razon_social IS NOT NULL AND nombre IS NULL AND apellidos IS NULL))
);

-- Cuentas: el ID es interno; hacia fuera se identifican por IBAN (sin espacios).
CREATE TABLE cuentas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iban VARCHAR(34) NOT NULL UNIQUE,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    saldo DECIMAL(19, 2) NOT NULL CHECK (saldo >= 0),
    moneda CHAR(3) NOT NULL,
    estado VARCHAR(10) DEFAULT 'ACTIVA' NOT NULL CHECK (estado IN ('ACTIVA', 'BLOQUEADA', 'CANCELADA')),
    fecha_apertura DATE DEFAULT CURRENT_DATE NOT NULL
);

CREATE TABLE transferencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_origen_id BIGINT NOT NULL REFERENCES cuentas(id),
    cuenta_destino_id BIGINT NOT NULL REFERENCES cuentas(id),
    importe DECIMAL(17, 2) NOT NULL CHECK (importe > 0),
    moneda CHAR(3) NOT NULL,
    -- Opcional, como en SEPA, y con su mismo límite de 140 caracteres.
    concepto VARCHAR(140),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CHECK (cuenta_origen_id <> cuenta_destino_id)
);

CREATE TABLE incidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transferencia_id BIGINT NOT NULL REFERENCES transferencias(id),
    regla VARCHAR(80) NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    prioridad VARCHAR(20) NOT NULL CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA')),
    estado VARCHAR(30) NOT NULL CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'RESUELTA')),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNIQUE (transferencia_id, regla)
);

CREATE TABLE cambios_incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id BIGINT NOT NULL REFERENCES incidencias(id),
    estado_anterior VARCHAR(30) NOT NULL,
    estado_nuevo VARCHAR(30) NOT NULL,
    comentario VARCHAR(1000),
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Empleados del banco que usan Countercheck (login y rol), no clientes.
CREATE TABLE usuarios (
    username VARCHAR(50) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    nombre_completo VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('EMPLEADO', 'SUPERVISOR')),
    activo BOOLEAN DEFAULT TRUE NOT NULL
);
